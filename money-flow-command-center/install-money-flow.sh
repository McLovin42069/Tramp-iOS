#!/usr/bin/env bash
# Money Flow Command Center - installer voor Linux (Kali/Debian/Ubuntu).
# Gebruik:  bash install-money-flow.sh
# Installeert in ~/money-flow-command-center, maakt een eigen Python-omgeving,
# en start de app automatisch (ook na herstart) op poort 8501, bereikbaar in je thuisnetwerk.
set -euo pipefail
DIR="${MFCC_DIR:-$HOME/money-flow-command-center}"
PORT="${MFCC_PORT:-8501}"
echo "==> Installeren in $DIR (poort $PORT)"
if ! python3 -c "import venv, ensurepip" 2>/dev/null; then
  echo "==> python3-venv ontbreekt; installeren (sudo wachtwoord kan gevraagd worden)"
  sudo apt-get update -y && sudo apt-get install -y python3-venv python3-pip
fi
mkdir -p "$DIR"
sed '1,/^__PAYLOAD__$/d' "$0" | base64 -d | tar -xz -C "$DIR"
python3 -m venv "$DIR/.venv"
"$DIR/.venv/bin/pip" install --quiet --upgrade pip
"$DIR/.venv/bin/pip" install --quiet -r "$DIR/requirements.txt"
cat > "$DIR/start.sh" <<START
#!/usr/bin/env bash
cd "$DIR"
exec "$DIR/.venv/bin/streamlit" run app.py --server.headless true --server.address 0.0.0.0 --server.port $PORT
START
chmod +x "$DIR/start.sh"
IP=$(hostname -I 2>/dev/null | awk '{print $1}'); IP=${IP:-localhost}
if [ "${MFCC_NO_SERVICE:-0}" != "1" ] && command -v systemctl >/dev/null && systemctl --user show-environment >/dev/null 2>&1; then
  mkdir -p "$HOME/.config/systemd/user"
  cat > "$HOME/.config/systemd/user/money-flow.service" <<UNIT
[Unit]
Description=Money Flow Command Center
After=network-online.target

[Service]
ExecStart=$DIR/start.sh
Restart=on-failure
RestartSec=5

[Install]
WantedBy=default.target
UNIT
  systemctl --user daemon-reload
  systemctl --user enable --now money-flow.service
  loginctl enable-linger "$USER" 2>/dev/null || echo "   (tip: 'sudo loginctl enable-linger $USER' laat de app draaien zonder ingelogd te zijn)"
  echo "==> Dienst 'money-flow' draait. Beheer: systemctl --user status|restart|stop money-flow"
else
  nohup "$DIR/start.sh" > "$DIR/app.log" 2>&1 &
  echo "==> Gestart op de achtergrond (log: $DIR/app.log). Opnieuw starten: $DIR/start.sh"
fi
echo
echo "KLAAR. Open op deze PC:      http://localhost:$PORT"
echo "       Op je telefoon (wifi): http://$IP:$PORT"
exit 0
